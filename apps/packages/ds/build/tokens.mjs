import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath, URL } from 'node:url';
import process from 'node:process';
import StyleDictionary from 'style-dictionary';

const packageRoot = fileURLToPath(new URL('../', import.meta.url));
const source = JSON.parse(
  await readFile(join(packageRoot, 'tokens/ds-v3.tokens.json'), 'utf8'),
);
// The reference groups are layers, not part of the flat {name} references.
// Keep its JSON untouched; normalize only Style Dictionary's input.
const definitions = Object.assign(
  {},
  source.primitive,
  source.semantic,
  source.component,
  source.deprecated,
);

StyleDictionary.registerTransform({
  name: 'ds/name',
  type: 'name',
  transform: (token) => `ds-${token.path.join('-')}`,
});
StyleDictionary.registerFormat({
  name: 'ds/typescript',
  format: ({ dictionary }) => {
    const values = Object.fromEntries(
      dictionary.allTokens.map((token) => [token.path.join('-'), token.$value]),
    );
    return [
      '// Generated by build/tokens.mjs. Do not edit.',
      '// prettier-ignore',
      `export const tokens = ${JSON.stringify(values, null, 2)} as const;`,
      '',
      'export type TokenName = keyof typeof tokens;',
      '',
    ].join('\n');
  },
});

const check = process.argv.includes('--check');
const output = check
  ? await mkdtemp(join(tmpdir(), 'vf-ds-tokens-'))
  : join(packageRoot, 'src');
try {
  const dictionary = new StyleDictionary({
    usesDtcg: true,
    tokens: definitions,
    platforms: {
      web: {
        transforms: ['ds/name'],
        buildPath: `${output}/`,
        files: [
          {
            destination: 'tokens.css',
            format: 'css/variables',
            options: { outputReferences: true, showFileHeader: false },
          },
          { destination: 'tokens.ts', format: 'ds/typescript' },
        ],
      },
    },
  });
  await dictionary.buildAllPlatforms();
  if (check) {
    for (const file of ['tokens.css', 'tokens.ts']) {
      const actual = await readFile(join(packageRoot, 'src', file), 'utf8');
      const expected = await readFile(join(output, file), 'utf8');
      if (actual !== expected) {
        throw new Error(
          `${file} is stale. Run npm run build in @vashfindir/ds.`,
        );
      }
    }
  }
} finally {
  if (check) await rm(output, { recursive: true, force: true });
}
