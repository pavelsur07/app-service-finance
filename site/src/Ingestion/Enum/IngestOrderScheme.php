<?php

declare(strict_types=1);

namespace App\Ingestion\Enum;

/**
 * Схема исполнения заказа.
 *
 * Хранится отдельно от источника, потому что наборы статусов у схем разные:
 * без явного различения нормализация превратилась бы в угадывание.
 */
enum IngestOrderScheme: string
{
    /** Со склада маркетплейса. */
    case FBO = 'fbo';

    /** Со склада продавца. */
    case FBS = 'fbs';

    /**
     * Источник не сообщил схему в понятном виде.
     *
     * Синтетическое значение вместо угадывания: у WB схема выводится из
     * названия склада, и незнакомая строка (опечатка, новый тип, расширение
     * API) не должна молча превращаться в одну из настоящих схем. Заказ при
     * этом сохраняется и попадает в видимую очередь на разбор — терять его
     * из-за незнакомого склада было бы хуже.
     */
    case UNKNOWN = 'unknown';

    public function label(): string
    {
        return match ($this) {
            self::FBO => 'Со склада маркетплейса',
            self::FBS => 'Со склада продавца',
            self::UNKNOWN => 'Схема не определена',
        };
    }
}
