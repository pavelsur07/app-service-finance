<?php

declare(strict_types=1);

namespace App\Ingestion\Infrastructure\Api\Wildberries;

/**
 * Ответ WB на запрос статусов: пригодные строки отдельно от отбракованных.
 *
 * Раньше первая же повреждённая строка выбрасывала исключение, и вместе с ней
 * терялись все корректные строки того же ответа. При текущих лимитах ответ —
 * это, как правило, всё подключение целиком, поэтому одна вечно кривая строка
 * навсегда блокировала обновление остальных заказов.
 *
 * Нарушение формы ВСЕГО ответа по-прежнему исключение: там пригодного нет
 * ничего. Отбракованные строки считаются и попадают в аудит вместе с
 * доказательством — молча их терять нельзя, иначе дефект интеграции выглядел
 * бы как отсутствие заказа у маркетплейса.
 */
final readonly class WbOrderStatusPage
{
    /**
     * @param array<int, array<string, mixed>> $statuses номер заказа => строка ответа
     * @param array<string, mixed>|null $evidence разобранный ответ целиком, если что-то отбраковано
     */
    public function __construct(
        public array $statuses = [],
        public int $rejectedRows = 0,
        public ?array $evidence = null,
    ) {
    }
}
