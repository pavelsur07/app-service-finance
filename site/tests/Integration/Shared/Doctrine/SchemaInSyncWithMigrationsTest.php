<?php

declare(strict_types=1);

namespace App\Tests\Integration\Shared\Doctrine;

use Doctrine\ORM\EntityManagerInterface;
use Doctrine\ORM\Mapping\ClassMetadata;
use Doctrine\ORM\Tools\SchemaTool;
use Symfony\Bundle\FrameworkBundle\Test\KernelTestCase;

/**
 * Гейт синхронности схемы: БД, накатанная миграциями (CI и локальные тесты собирают её только так),
 * совпадает со схемой из маппинга Doctrine и SchemaExtension модулей.
 *
 * Без него `doctrine:migrations:diff` копит ложные расхождения, и сгенерированная миграция
 * удаляет живые таблицы, внешние ключи и частичные уникальные индексы (на 03.11.2026 их было 409 строк).
 *
 * Что делать при падении:
 * - новая сущность или колонка без миграции → написать миграцию;
 * - объект есть только в миграции (DBAL-таблица, ключ на `string $companyId`, частичный индекс) →
 *   описать в `{Module}/Infrastructure/Doctrine/*SchemaExtension` ({@see \App\Shared\Infrastructure\Doctrine\Schema\SchemaExtension});
 * - атрибут расходится с миграцией (default, длина, jsonb, имя индекса) → поправить атрибут под БД.
 *
 * KNOWN_DRIFT — расхождения, которые закрывает миграция этапа 3 (docs/tasks/doctrine-schema-sync).
 * Новые записи сюда не добавлять; исчезнувшая запись роняет тест, чтобы список только сокращался.
 */
final class SchemaInSyncWithMigrationsTest extends KernelTestCase
{
    private const KNOWN_DRIFT = [
        // Неиспользуемые таблицы: удаление — решение Владельца (этап 3).
        'ALTER TABLE balance_categories DROP CONSTRAINT fk_6250404a727aca70',
        'ALTER TABLE balance_category_links DROP CONSTRAINT fk_balance_link_category',
        'DROP TABLE balance_categories',
        'DROP TABLE balance_category_links',
        'DROP TABLE document_counterparty_repair_backup',
        // Ключ потерян миграцией Version20260115105426: маппинг прав, БД вернёт миграция.
        'ALTER TABLE document_operations ADD CONSTRAINT FK_89D7F81E85D43DF4 FOREIGN KEY (project_direction_id) REFERENCES project_directions (id) NOT DEFERRABLE',
        // Дубли уникальных индексов по тем же колонкам.
        'DROP INDEX idx_month_close_lookup',
        'DROP INDEX idx_marketplace_order',
        'DROP INDEX idx_moysklad_connections_company_name',
        // Очередь failed (doctrine-транспорт Messenger): таблица из миграции старше схемы транспорта.
        'DROP INDEX idx_75ea56e016ba31db',
        'DROP INDEX idx_75ea56e0e3bd61ce',
        'DROP INDEX idx_75ea56e0fb7336f0',
        'ALTER TABLE messenger_messages ALTER id DROP DEFAULT',
        'ALTER TABLE messenger_messages ALTER id ADD GENERATED BY DEFAULT AS IDENTITY',
        'CREATE INDEX IDX_75EA56E0FB7336F0E3BD61CE16BA31DBBF396750 ON messenger_messages (queue_name, available_at, delivered_at, id)',
    ];

    /**
     * Служебная таблица doctrine/migrations: в консоли её скрывает фильтр бандла миграций,
     * в тестовом ядре фильтра нет. Не расхождение.
     */
    private const MIGRATIONS_TABLE = 'DROP TABLE doctrine_migration_versions';

    /** Остатки комментариев `(DC2Type:…)` DBAL 3; снимает миграция этапа 3. */
    private const LEGACY_TYPE_COMMENT = "/^COMMENT ON COLUMN [a-z_\"]+\\.[a-z_\"]+ IS ''$/";

    public function testMigratedDatabaseMatchesMapping(): void
    {
        $statements = $this->updateSchemaSql();

        $unexpected = array_values(array_filter(
            $statements,
            static fn (string $sql): bool => !\in_array($sql, self::KNOWN_DRIFT, true)
                && 1 !== preg_match(self::LEGACY_TYPE_COMMENT, $sql),
        ));

        self::assertSame([], $unexpected, 'Схема из маппинга расходится с БД после миграций. Что делать — в docblock теста.');
    }

    public function testKnownDriftListOnlyShrinks(): void
    {
        $stale = array_values(array_diff(self::KNOWN_DRIFT, $this->updateSchemaSql()));

        self::assertSame([], $stale, 'Расхождение исправлено — удалите запись из KNOWN_DRIFT.');
    }

    /** @return list<string> */
    private function updateSchemaSql(): array
    {
        self::bootKernel();
        $em = self::getContainer()->get(EntityManagerInterface::class);

        // Тестовые фикстуры (tests/Fixtures/Doctrine) создают свои таблицы сами.
        $metadata = array_values(array_filter(
            $em->getMetadataFactory()->getAllMetadata(),
            static fn (ClassMetadata $meta): bool => !str_starts_with($meta->getName(), 'App\\Tests\\'),
        ));

        return array_values(array_filter(
            (new SchemaTool($em))->getUpdateSchemaSql($metadata),
            static fn (string $sql): bool => self::MIGRATIONS_TABLE !== $sql,
        ));
    }
}
